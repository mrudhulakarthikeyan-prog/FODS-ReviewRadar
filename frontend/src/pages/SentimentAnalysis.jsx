import React, { useState } from 'react';
import axios from 'axios';

export default function SentimentAnalysis() {
  const [review, setReview] = useState('');
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const analyse = async () => {
    if (!review.trim()) return;
    setLoading(true); setError(''); setResult(null);
    try {
      const response = await axios.post('/api/predict', { reviews: [review] });
      setResult(response.data.predictions?.[0]);
    } catch (e) {
      setError(e.response?.data?.error || 'Prediction could not be completed. Please try again.');
    } finally { setLoading(false); }
  };

  const tone = result?.sentiment?.toLowerCase() || 'neutral';
  return (
    <section className="page">
      <div className="page-heading"><div><p className="eyebrow">QUICK CHECK</p><h1>Sentiment Analysis</h1><p>Understand the overall tone of an individual customer review.</p></div></div>
      <div className="card">
        <label className="field-label" htmlFor="review-text">Customer review</label>
        <textarea id="review-text" rows="6" value={review} onChange={e => setReview(e.target.value)} placeholder="Paste a customer review here…" />
        <button className="primary-button" onClick={analyse} disabled={loading || !review.trim()}>{loading ? 'Analysing…' : 'Analyse sentiment'}</button>
        {error && <p className="error">{error}</p>}
        {result && <div className={`result-panel sentiment-${tone}`}>
          <span>Predicted sentiment</span>
          <h2>{result.sentiment}</h2>
          {result.confidence != null && <p>Prediction confidence: {(result.confidence * 100).toFixed(1)}%</p>}
          {result.review_needed && <p className="review-note">This review contains mixed or unclear signals. Please review it manually before relying on the result.</p>}
          <small>{result.method === 'lexical_support' ? 'Prediction supported by clear language cues and the trained model.' : 'Prediction generated by the trained review classifier.'}</small>
        </div>}
      </div>
    </section>
  );
}
